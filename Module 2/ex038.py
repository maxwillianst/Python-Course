print('======= Qual é o menor e maior =======')

n1 = int(input('Primeiro valor: '))
n2 = int(input('Segundo valor: '))
if n1 > n2:
    print(f'O primeiro valor é o maior')
elif n2 > n1:
    print(f'O segundo valor é o maior')
else:
    print('Ambos são iguais')


